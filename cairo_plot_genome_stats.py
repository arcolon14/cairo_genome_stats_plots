def hex_to_rgb(hex_color):
    '''Convert a hex color (e.g., #ff0000) to an RGB tuple in the [0, 1] range.'''
    hex_color = hex_color.lstrip('#')
    assert len(hex_color) == 6
    return tuple( int(hex_color[i:i+2], 16)/255.0 for i in (0, 2, 4) )

def set_palette(name=PALETTE, reverse=False):
    '''
    Get the RGB colors of a given palette, ordered from the lowest
    to the highest values (reversed if specified).
    '''
    assert name in PALETTES, f'Error: Palette {name} not available.'
    palette = [ hex_to_rgb(color) for color in PALETTES[name] ]
    assert len(palette) >= 3 and len(palette) % 2 == 1
    if reverse:
        palette = palette[::-1]
    return palette


# DEPRECATED: Not used for plotting since the adjusted values are now log2
# enrichments centered at 0. Kept for reference; see `diverging_color_gradient()`.
def scale_sigmoid_color_mean(mean, val):
    '''
    Plot the values using a Gompertz curve: y(t) = ae^(-be(^-ct))
      https://en.wikipedia.org/wiki/Gompertz_function
    The X-axis scales from 0 to 10, Y-axis from 0 to 1; we have shifted
    the curve to the right by subtracting 2 from val; we will shit it 
    more to line the sigmoid curve up with the mean value.
    '''
    val  = math.fabs(val)
    val  = val * 10
    mean = mean * 10 / 2
    a    = 1
    b    = 1
    c    = 0.5
    val  = a * math.exp(-1 * b * (math.exp(-1 * c * (val - 2 - mean))))
    return val

# DEPRECATED: Not used for plotting since the adjusted values are now log2
# enrichments centered at 0. Kept for reference; see `diverging_color_gradient()`.
def three_color_gradient(rgb1, rgb2, rgb3, mean, alpha, max_scale):
    (r1, g1, b1) = rgb1
    (r2, g2, b2) = rgb2
    (r3, g3, b3) = rgb3

    # Adjust mean and alpha so that max value is 1.0
    adj_mean = mean/max_scale
    adj_alpha = alpha/max_scale
    adj_alpha = scale_sigmoid_color_mean(adj_mean, adj_alpha)
    # scaled_alpha = float(alpha)
    if (adj_alpha < adj_mean):
        # scaled_alpha = float(alpha) / mean
        scaled_alpha = float(adj_alpha) / adj_mean
        r = ((1.0 - scaled_alpha) * r1) + (scaled_alpha * r2)
        g = ((1.0 - scaled_alpha) * g1) + (scaled_alpha * g2)
        b = ((1.0 - scaled_alpha) * b1) + (scaled_alpha * b2)
    else:
        # scaled_alpha = float(alpha - mean) / (1.0 - mean)
        scaled_alpha = float(adj_alpha - adj_mean) / (1.0 - adj_mean)
        r = (scaled_alpha * r3) + ((1.0 - scaled_alpha) * r2)
        g = (scaled_alpha * g3) + ((1.0 - scaled_alpha) * g2)
        b = (scaled_alpha * b3) + ((1.0 - scaled_alpha) * b2)
    return (r, g, b)

def diverging_color_gradient(palette, value, scale_min, scale_max):
    '''
    Map a log2 enrichment value to a color on a diverging scale centered
    at 0 (the genome-wide average). Negative values are scaled to the lower
    half of the palette based on scale_min, and positive values to the upper
    half based on scale_max, so each side can have a different range. Values
    are clamped to [scale_min, scale_max]. The palette is a list of RGB colors
    ordered from the lowest to the highest values, with the middle color at 0;
    colors are linearly interpolated between consecutive stops.
    '''
    assert scale_min < 0 < scale_max
    assert len(palette) >= 3 and len(palette) % 2 == 1
    # Scale to [-1, 1], and then to a position along the palette stops
    if value >= 0:
        scaled = min(1.0, value/scale_max)
    else:
        scaled = max(-1.0, value/math.fabs(scale_min))
    position = ((scaled + 1.0)/2.0) * (len(palette) - 1)
    i = min(int(position), len(palette) - 2)
    frac = position - i
    (r, g, b) = [ ((1.0 - frac) * low) + (frac * high)
                  for low, high in zip(palette[i], palette[i+1]) ]
    return (r, g, b)

