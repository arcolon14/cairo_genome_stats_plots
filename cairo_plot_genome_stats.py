# Process the chromosomes
#
def process_chromosomes(chromosomes, chrom_order, wins_dict, image, 
                        context, max_grd, scale_min, scale_max, palette,
                        plot_type='proportion', scale=SCALE, step=STEP):
    assert type(chromosomes) is dict
    assert isinstance(list(chromosomes.values())[0], Chromosome)
    assert type(wins_dict) is dict
    assert isinstance(image, Image)
    assert len(chromosomes) == len(chrom_order)
    assert plot_type in ['proportion', 'count']

    # Plot the chromosomes and values
    chr_step = (image.max_tck-image.min_tck)/len(chromosomes)
    min_step = chr_step/4
    y = image.min_tck

    ## Loop over the chromosomes
    for chromosome in chrom_order:
        assert chromosome in chromosomes
        # Define the boundaries of the chromosome
        bp = chromosomes[chromosome].len
        x1 = image.min_chr
        x2 = image.scale_bp_to_pix(bp, max_grd)
        y1 = y+(1*min_step)
        y2 = y+(3*min_step)

        # Extract the windows for the current chromosome
        for window in wins_dict[chromosome]:
            assert isinstance(window, WindowStat)
            if window.mid > bp:
                continue
            x = image.scale_bp_to_pix(window.mid, max_grd)
            # Select the corresponding value type to plot
            value = window.proportion
            if plot_type == 'count':
                value = window.n_elements
            # Scale the colors based on the log2 enrichment
            (r, g, b) = diverging_color_gradient(palette, value, scale_min, scale_max)
            # Plot a line for the midpoint of a given window.
            # Not a polygon to prevent overlapping between windows.
            context.set_dash([])
            context.move_to(x, y1)
            context.line_to(x, y2)
            context.set_source_rgb(r, g, b)
            context.stroke()

        # Add the Chromosome len boxes
        context.set_dash([])
        context.move_to(x1, y1)
        context.line_to(x2, y1)
        context.line_to(x2, y2)
        context.line_to(x1, y2)
        context.close_path()
        context.set_line_width(1.0)
        col = ChromColors('border')
        context.set_source_rgb(col.r, col.g, col.b)
        # context.stroke_preserve()
        context.stroke()
        # col = ChromColors('fill')
        # context.set_source_rgb(col.r, col.g, col.b)
        # context.fill()

        # Add the labels
        label = str(chromosomes[chromosome].name)
        label_height = context.text_extents(label)[3]
        label_width = context.text_extents(label)[0] + context.text_extents(label)[2]
        # Right-align the labels next to the start of the chromosomes
        lab_x = image.chr_lab-label_width
        lab_y = (y+(2*min_step))+(label_height/2)
        txt_col = ChromColors('text')
        context.move_to(lab_x, lab_y)
        context.set_source_rgb(txt_col.r, txt_col.g, txt_col.b)
        context.show_text(label)
        y += chr_step

