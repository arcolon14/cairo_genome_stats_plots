# Class to set the settings to the image output
class Image:
    def __init__(self, height=IMG_HEIGHT, width=IMG_WIDTH, font_size=FONT_SIZE, 
                 img_type='pdf', offset=25, edge=15):
        assert offset > edge
        # General Plot info
        self.height = height
        self.width  = width
        self.font   = font_size
        self.type   = img_type
        self.edge   = edge
        self.offset = offset
        self.max_y  = edge
        self.min_y  = height-edge
        self.min_x  = edge
        self.max_x  = width-edge
        # Position for the objects
        self.min_chr = offset
        self.max_chr = self.max_x
        self.min_tck = self.max_y
        self.max_tck = height-offset
        # Position for labels
        self.len_lab = height-edge
        self.chr_lab = offset-edge
    def fit_chrom_labels(self, context, labels, pad=5):
        '''
        Place the start of the chromosomes after the widest chromosome
        label, so that the labels are not cut off at the left edge.
        The labels are right-aligned to self.chr_lab.
        '''
        context.set_font_size(self.font)
        # Width of the label from the drawing point, including the bearing
        max_width = max([ context.text_extents(label)[0] + context.text_extents(label)[2]
                          for label in labels ])
        self.min_chr = max(self.offset, self.min_x + max_width + pad)
        self.chr_lab = self.min_chr - pad
    def scale_bp_to_pix(self, pos_bp, max_bp):
        scaled_x = ((pos_bp/max_bp)*(self.max_chr - self.min_chr)) + self.min_chr
        return scaled_x
    def cairo_context(self, plot_out_dir):
        if self.type == 'pdf':
            surface = cairo.PDFSurface(plot_out_dir, self.width, self.height)
            context = cairo.Context(surface)
            return surface, context
        elif self.type == 'svg':
            surface = cairo.SVGSurface(plot_out_dir, self.width, self.height)
            context = cairo.Context(surface)
            return surface, context
        else:
            sys.exit("The only supported formats are \'PDF\' and \'SVG\'.")


